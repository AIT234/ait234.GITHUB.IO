export function getStatusBadgeVariant(status: ProjectStatus): string {
  const variants: Record<ProjectStatus, string> = {
    planning: "outline",
    tendering: "secondary",
    in_progress: "default",
    delayed: "destructive",
    completed: "default",
    cancelled: "outline",
  };
  return variants[status];
}

export function getCategoryIcon(category: ProjectCategory): string {
  return categoryEmojis[category];
}

export function formatCurrency(amount: number): string {
  if (amount >= 1000000000000) return `₦${(amount / 1000000000000).toFixed(1)}T`;
  if (amount >= 1000000000) return `₦${(amount / 1000000000).toFixed(1)}B`;
  if (amount >= 1000000) return `₦${(amount / 1000000).toFixed(1)}M`;
  return `₦${amount.toLocaleString()}`;
}

export function formatDate(date: string): string {
  return new Date(date).toLocaleDateString("en-NG", {
    year: "numeric",
    month: "short",
    day: "numeric",
  });
}

export function getOverallStats() {
  const total = mockProjects.length;
  const active = mockProjects.filter((p) => p.status === "in_progress").length;
  const completed = mockProjects.filter((p) => p.status === "completed").length;
  const delayed = mockProjects.filter((p) => p.status === "delayed").length;
  const planning = mockProjects.filter((p) => p.status === "planning" || p.status === "tendering").length;
  const totalBudget = mockProjects.reduce((sum, p) => sum + p.budget, 0);
  const totalSpent = mockProjects.reduce((sum, p) => sum + p.spent, 0);
  const avgCompletion = Math.round(mockProjects.reduce((sum, p) => sum + p.completion, 0) / total);
  return { total, active, completed, delayed, planning, totalBudget, totalSpent, avgCompletion };
}